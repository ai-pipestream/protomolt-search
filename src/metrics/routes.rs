//! The fixed route set and its label names.

/// One RPC route the exporter counts. The discriminant is the index
/// into every per-route table, so the table order in `REQUEST_ROUTES`
/// must match this declaration order (a unit test pins it).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(usize)]
pub enum Route {
    // Node (shard) routes.
    SearchShard,
    StreamSearch,
    BrowseShard,
    ResolveFilterBitmap,
    HybridShard,
    ShardLegs,
    Bm25Query,
    Bm25PhraseQuery,
    Bm25QueryStream,
    ReadWal,
    TermStats,
    ExpandTermPrefix,
    VectorRescore,
    ExactVectorRescore,
    Bm25Rescore,
    FetchValues,
    AggregateShard,
    QuantileCounts,
    GetDocuments,
    ResolveParents,
    AddDocuments,
    AddVectors,
    IngestMapped,
    DeleteDocuments,
    CommitReplacements,
    SuggestTerms,
    Suggest,
    TermSuggest,
    CompactShard,
    ExportSnapshot,
    StreamSnapshot,
    InstallSnapshotFrom,
    // Coordinator public routes.
    Search,
    Bm25Search,
    PhraseSearch,
    HybridSearch,
    Query,
    QueryStream,
    PlanIndex,
    RoutedIngestMapped,
    FreezeTopologyWrites,
    PublishTopology,
    AbortTopologyCutover,
    Aggregate,
    ClusterHealth,
    BroadcastVectorBackend,
    VariantSearch,
    // Cluster control routes.
    RegisterNode,
    RenewNodeLease,
    DrainNode,
    ReportShard,
    CompletePlacementAction,
    ReconcileCluster,
    GetClusterPlan,
    RollbackCluster,
    // Diagnostics, on both nodes and coordinators.
    GetRuntimeKnobs,
    SetRuntimeKnob,
    GetMetricsSnapshot,
    StreamMetrics,
    GetShardDiagnostics,
    RecentQueries,
    /// `SearchService.PlanPlacement`.
    PlanPlacement,
    DescribeSchema,
    /// `ClusterControl.PlanBalance`.
    PlanBalance,
    /// `NodeService.EvaluateBoolean`.
    EvaluateBoolean,
    GetDocumentWriteTarget,
    GetDocumentPublicationStatus,
    AcceptSourceDocument,
    /// `RaftOperatorService.GetMemberStatus`.
    GetMemberStatus,
    /// `RaftOperatorService.AddLearner`.
    AddLearner,
    /// `RaftOperatorService.PromoteLearners`.
    PromoteLearners,
    /// `RaftOperatorService.RemoveMember`.
    RemoveMember,
    /// `RaftOperatorService.VerifyPublishedImage`.
    VerifyPublishedImage,
    /// `NodeService.ScoreSplade`.
    ScoreSplade,
}

